const {JSDOM}=require('jsdom');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
  const base=path.join(__dirname,'..'),html=fs.readFileSync(path.join(base,'index.html'),'utf8');
  const dom=new JSDOM(html,{url:'https://jessieyueh.github.io/senior-ktv-song-request/',runScripts:'outside-only'}),w=dom.window,d=w.document;
  const restored=[];
  w.scrollTo=(x,y)=>restored.push([x,y]);
  Object.defineProperty(w,'scrollY',{value:240,writable:true});
  w.HTMLElement.prototype.scrollIntoView=()=>{};
  w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};
  w.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');this.dispatchEvent(new w.Event('close'));};
  w.KTVPlayback=class{stop(){}setPaused(){}};
  for(const name of ['favorites.js','catalog-sort.js','stroke-sort.js','ost-2026.js','mandarin-song-pack.js','qrcode.js'])w.eval(fs.readFileSync(path.join(base,name),'utf8'));
  w.eval(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
  const click=id=>d.getElementById(id).click(),flush=()=>new Promise(r=>setImmediate(r));
  click('catalogTab');await flush();
  assert.ok(d.documentElement.classList.contains('dialogOpen'));
  assert.ok(d.body.classList.contains('dialogOpen'));
  assert.equal(d.body.style.getPropertyValue('--dialog-page-top'),'-240px');
  assert.notEqual(d.activeElement.id,'search','opening the book must not summon the phone keyboard');
  click('chooseSinger');await flush();
  assert.equal(d.querySelectorAll('dialog[open]').length,2);
  click('closeSinger');await flush();
  assert.equal(restored.length,0,'closing a child dialog must keep the parent and page locked');
  assert.ok(d.body.classList.contains('dialogOpen'));
  click('closeBook');await flush();
  assert.ok(!d.body.classList.contains('dialogOpen'));
  assert.ok(!d.documentElement.classList.contains('dialogOpen'));
  assert.deepEqual(restored,[[0,240]],'the last dialog restores the original page position once');
  w.scrollY=350;click('catalogTab');click('chooseSinger');
  // Escape/native dialog dismissal removes the open attribute without going through a button.
  d.getElementById('singerDialog').removeAttribute('open');await flush();
  assert.ok(d.body.classList.contains('dialogOpen'));
  d.getElementById('catalogDialog').removeAttribute('open');await flush();
  assert.deepEqual(restored,[[0,240],[0,350]]);
  assert.equal(d.body.style.getPropertyValue('--dialog-page-top'),'');
  w.scrollY=90;click('catalogTab');d.getElementById('catalogDialog').close();click('cloudBtn');await flush();
  assert.equal(restored.length,3);
  assert.ok(d.body.classList.contains('dialogOpen'),'switching dialogs keeps the new view locked');
  click('closeCloudBtn');await flush();
  assert.ok(!d.body.classList.contains('dialogOpen'));
  console.log('PASS modal stack lock, keyboard focus, native dismissal, page position restoration and dialog switching');
  dom.window.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
